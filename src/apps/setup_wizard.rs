//! First-run setup wizard for LobsterOS
//!
//! On first boot, if /etc/lobsteros.conf doesn't exist, the wizard runs:
//! 1. Welcome screen
//! 2. Language/timezone selection
//! 3. WiFi network configuration
//! 4. User account creation (username, password)
//! 5. System information (hostname)
//! 6. Writes config to /etc/lobsteros.conf

use crate::println;
use alloc::string::String;

/// Setup wizard state
pub struct SetupWizard {
    pub step: u8,
    pub hostname: String,
    pub timezone: String,
    pub wifi_ssid: String,
    pub wifi_password: String,
    pub username: String,
    pub password: String,
    pub language: String,
    pub completed: bool,
}

impl SetupWizard {
    pub fn new() -> Self {
        Self {
            step: 0,
            hostname: String::from("lobster"),
            timezone: String::from("UTC"),
            wifi_ssid: String::new(),
            wifi_password: String::new(),
            username: String::from("admin"),
            password: String::new(),
            language: String::from("en_US"),
            completed: false,
        }
    }

    /// Advance to next step
    pub fn next_step(&mut self) -> bool {
        self.step += 1;
        if self.step > 5 {
            self.completed = true;
            self.finish();
            true
        } else {
            false
        }
    }

    /// Get current step name
    pub fn step_name(&self) -> &'static str {
        match self.step {
            0 => "Welcome",
            1 => "Language & Timezone",
            2 => "WiFi Configuration",
            3 => "User Account",
            4 => "Hostname",
            5 => "Confirmation",
            _ => "Complete",
        }
    }

    /// Get instructions for current step
    pub fn step_instructions(&self) -> &'static str {
        match self.step {
            0 => "Welcome to LobsterOS! Press Next to begin setup.",
            1 => "Select your language and timezone.",
            2 => "Enter your WiFi network name (SSID) and password.",
            3 => "Create your user account. This will be your login.",
            4 => "Set your system hostname (computer name on network).",
            5 => "Review your settings and confirm to complete setup.",
            _ => "",
        }
    }

    /// Generate config file content
    pub fn generate_config(&self) -> String {
        let mut config = String::new();
        config.push_str("# LobsterOS Configuration\n");
        config.push_str("# Generated by first-run setup wizard\n\n");
        config.push_str("[system]\n");
        config.push_str(&alloc::format!("hostname = \"{}\"\n", self.hostname));
        config.push_str(&alloc::format!("timezone = \"{}\"\n", self.timezone));
        config.push_str(&alloc::format!("language = \"{}\"\n", self.language));
        config.push_str("\n[wifi]\n");
        config.push_str(&alloc::format!("ssid = \"{}\"\n", self.wifi_ssid));
        config.push_str("password = \"***\"\n");
        config.push_str("auto_connect = true\n");
        config.push_str("\n[user]\n");
        config.push_str(&alloc::format!("name = \"{}\"\n", self.username));
        config.push_str("password = \"***\"\n");
        config.push_str("shell = \"/bin/lobster-sh\"\n");
        config
    }

    /// Finish setup — write config and mark as done
    fn finish(&self) {
        println!("[setup] First-run setup complete!");
        println!("[setup] Hostname: {}", self.hostname);
        println!("[setup] Timezone: {}", self.timezone);
        println!("[setup] Language: {}", self.language);
        println!("[setup] User: {}", self.username);
        if !self.wifi_ssid.is_empty() {
            println!("[setup] WiFi: {} (auto-connect)", self.wifi_ssid);
        }

        // Write config file to /etc/lobsteros.conf
        let config = self.generate_config();
        match crate::fs::vfs::create("/etc/lobsteros.conf") {
            Ok(_) => {
                if let Ok(fd) = crate::fs::vfs::open("/etc/lobsteros.conf", 1) {
                    let _ = crate::fs::vfs::write(fd, config.as_bytes());
                }
                println!("[setup] Config written to /etc/lobsteros.conf");
            }
            Err(e) => {
                println!("[setup] Warning: Could not write config: {:?}", e);
            }
        }
    }
}

impl Default for SetupWizard {
    fn default() -> Self {
        Self::new()
    }
}

/// Check if first-run setup is needed
pub fn is_first_run() -> bool {
    // Check if /etc/lobsteros.conf exists
    crate::fs::vfs::stat("/etc/lobsteros.conf").is_none()
}

/// Global wizard instance
static mut WIZARD: Option<SetupWizard> = None;

/// Initialize and start the setup wizard (if first run)
pub fn init() {
    if is_first_run() {
        println!("[setup] First boot detected — starting setup wizard");
        unsafe {
            WIZARD = Some(SetupWizard::new());
        }
    } else {
        println!("[setup] Config found — skipping first-run setup");
    }
}

/// Get the wizard instance (if active)
pub fn get_wizard() -> Option<&'static mut SetupWizard> {
    unsafe { WIZARD.as_mut() }
}

/// Check if wizard is active
pub fn is_active() -> bool {
    unsafe { WIZARD.is_some() && WIZARD.as_ref().map(|w| !w.completed).unwrap_or(false) }
}
