//! Writes the sprite blob and the generated Rust index.

use crate::Entry;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

fn variants(entries: &[Entry], out: &mut String) {
    for entry in entries {
        let _ = writeln!(out, "    /// {} sprite.\n    {},", entry.variant, entry.variant);
    }
}

fn sprite_table(entries: &[Entry], offsets: &[Vec<u32>]) -> String {
    let mut out = String::new();
    for (entry, offs) in entries.iter().zip(offsets) {
        out += "    [";
        for (sprite, offset) in entry.sprites.iter().zip(offs) {
            let _ = write!(out, "Sprite {{ size: {}, offset: {offset} }}, ", sprite.size);
        }
        out += "],\n";
    }
    out
}

fn enum_block(name: &str, doc: &str, entries: &[Entry]) -> String {
    let mut out = format!(
        "/// {doc}\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum {name} {{\n"
    );
    variants(entries, &mut out);
    out += "}\n\n";
    let _ = writeln!(out, "impl {name} {{\n    /// Every variant, in sprite-table order.\n    pub const ALL: [{name}; {}] = [", entries.len());
    for entry in entries {
        let _ = writeln!(out, "        {name}::{},", entry.variant);
    }
    out += "    ];\n}\n\n";
    out
}

/// Writes `icons.bin` and `index.rs` into `dir`. Returns the blob size.
pub fn write(dir: &Path, icons: &[Entry], glyphs: &[Entry]) -> Result<usize, String> {
    let mut blob = Vec::new();
    let mut tables = Vec::new();
    for group in [icons, glyphs] {
        let mut offsets = Vec::new();
        for entry in group {
            offsets.push(
                entry
                    .sprites
                    .iter()
                    .map(|s| {
                        let at = blob.len() as u32;
                        blob.extend_from_slice(&s.data);
                        at
                    })
                    .collect::<Vec<u32>>(),
            );
        }
        tables.push(offsets);
    }
    let mut index = String::from("// @generated by tools/icongen. Do not edit.\n\n");
    index += &enum_block("Icon", "A full-colour icon (app tile or file type).", icons);
    index += &enum_block("Glyph", "A symbolic glyph drawn as a tinted alpha mask.", glyphs);
    let _ = write!(
        index,
        "/// Sprite locations per icon, in [`Icon::ALL`] order.\npub(crate) static ICON_SPRITES: [[Sprite; 3]; {}] = [\n{}];\n\n\
         /// Sprite locations per glyph, in [`Glyph::ALL`] order.\npub(crate) static GLYPH_SPRITES: [[Sprite; 3]; {}] = [\n{}];\n",
        icons.len(),
        sprite_table(icons, &tables[0]),
        glyphs.len(),
        sprite_table(glyphs, &tables[1]),
    );
    fs::write(dir.join("icons.bin"), &blob).map_err(|e| format!("write icons.bin: {e}"))?;
    fs::write(dir.join("index.rs"), index).map_err(|e| format!("write index.rs: {e}"))?;
    Ok(blob.len())
}
